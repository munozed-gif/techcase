function generateBcsetActivationScript(packages, mode = 'U') {
  const bcsets = packages.filter(p => p.type === 'bcset');
  const bbs    = packages.filter(p => p.type === 'building_block');
  const today  = new Date().toISOString().slice(0, 10).replace(/-/g, '');

  const bcsetLines = bcsets.map(p => `      ( '${p.name}' )`).join('\n');
  const bbLines    = bbs.map(p => `*   Building Block: ${p.name}${p.description ? ' - ' + p.description : ''}`).join('\n');

  return `REPORT Z_TCBCSET_ACTIVATE.
*&-----------------------------------------------------*
*& BCset Activation Script — Generated by TechCase
*& Date: ${today}
*& Mode: ${mode === 'U' ? 'U = Update existing values' : 'O = Overwrite all values'}
*&-----------------------------------------------------*
${bbs.length > 0 ? `*\n* Building Blocks to review manually:\n${bbLines}\n*` : ''}
DATA: lv_subrc   TYPE sysubrc,
      lt_msg     TYPE TABLE OF scprm_message,
      ls_msg     LIKE LINE OF lt_msg.

DATA(lt_bcsets) = VALUE string_table(
${bcsetLines || "      ( '' ) \" Add BCset names here"}
).

LOOP AT lt_bcsets INTO DATA(lv_name).
  CHECK lv_name IS NOT INITIAL.
  WRITE: / 'Activating:', lv_name.

  CALL FUNCTION 'SCPR_ACTIVATE_IN_CLIENT'
    EXPORTING
      p_bcset_name        = CONV scpr_bcset_name( lv_name )
      p_modus             = '${mode}'
    TABLES
      p_messages          = lt_msg
    EXCEPTIONS
      bcset_not_found     = 1
      activation_error    = 2
      OTHERS              = 3.

  lv_subrc = sy-subrc.

  IF lv_subrc = 0.
    WRITE: / '  -> OK'.
  ELSE.
    WRITE: / '  -> ERROR (subrc =', lv_subrc, ')'.
    LOOP AT lt_msg INTO ls_msg.
      WRITE: / '     ', ls_msg-message.
    ENDLOOP.
  ENDIF.
  CLEAR lt_msg.
ENDLOOP.

WRITE: / '--- Activation complete ---'.`;
}

